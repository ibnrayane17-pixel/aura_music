/// Looks in the extra strings first, then in the main ones, then in English.
String translateAll(String lang, String key, {Map<String, String>? args}) {
  String text = kExtraStrings[lang]?[key] ??
      kMoreStrings[lang]?[key] ??
      kStrings[lang]?[key] ??
      kExtraStrings['en']?[key] ??
      kMoreStrings['en']?[key] ??
      kStrings['en']?[key] ??
      key;
  if (args != null) {
    args.forEach((String name, String value) {
      text = text.replaceAll('{$name}', value);
    });
  }
  return text;
}
